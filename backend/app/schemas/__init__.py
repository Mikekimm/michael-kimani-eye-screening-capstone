# ---------- patients ----------

class PatientCreate(BaseModel):
    """Leave ``code`` out and the server generates one. A device that registers a patient offline sends
    the code it generated with the same algorithm; it must carry a valid check character."""
    model_config = ConfigDict(extra="forbid")
    code: str | None = None
    year_of_birth: int | None = Field(default=None, ge=1900, le=2100)
    sex: Sex = Sex.UNKNOWN
    has_diabetes: bool | None = None
    client_uuid: str | None = Field(default=None, max_length=36)

    @field_validator("code")
    @classmethod
    def _valid_generated_code(cls, value: str | None) -> str | None:
        if value is None:
            return None
        if not patient_codes.is_valid(value):
            raise ValueError("Patient codes are generated by the app (e.g. PHC-7K3Q9W); this one is not valid.")
        return value.strip().upper()


